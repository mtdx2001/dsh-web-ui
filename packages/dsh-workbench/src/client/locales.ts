export type WorkbenchKey = keyof typeof zh

/** The dictionary namespace this plugin owns. */
export const NS = 'workbench'

/** Format one copy string with {name} placeholders. */
export function format(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`))
}

/** Simple dictionary access (zh/en by a global flag the client sets). */
export const dictionaries: Record<'zh' | 'en', Record<WorkbenchKey, string>> = { zh, en }

let currentLanguage: 'zh' | 'en' = 'zh'

/** Set the active language (the client mirrors the shell's <html lang>). */
export function setLanguage(language: string): void {
  currentLanguage = language === 'en' ? 'en' : 'zh'
}

/** Current language (the tab label is stamped into injected DOM). */
export function language(): 'zh' | 'en' {
  return currentLanguage
}

/** Translate one key with optional params. */
export function t(key: WorkbenchKey, params?: Record<string, string | number>): string {
  const table = dictionaries[currentLanguage] ?? zh
  const template = table[key] ?? zh[key]
  return params === undefined ? template : format(template, params)
}
